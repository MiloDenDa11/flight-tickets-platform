import 'express-async-errors';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import { env } from './config/env';
import routes from './routes';
import { errorHandler } from './middlewares/errorHandler.middleware';
const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: env.FRONTEND_URL, credentials: true }));
app.use(express.json({ limit: '100kb' }));
app.use(cookieParser());
app.use('/api', rateLimit({ windowMs: 60000, limit: 180, standardHeaders: 'draft-8', legacyHeaders: false, message: { success: false, message: 'Bạn gửi yêu cầu quá nhanh. Vui lòng thử lại.' } }));
app.use('/api/v1', routes);
app.use((_req, res) => { res.status(404).json({ success: false, message: 'Endpoint không tồn tại' }); });
app.use(errorHandler);
export default app;
